// Writes src/content/patho/image-sizes.ts: the byte length of every course image.
// Image approvals hash this, so replacing a file sends the image back for review.
// Runs before dev, build and typecheck (package.json pre-scripts).
import { readdirSync, statSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const dir = "public/images/patho";
const out = "src/content/patho/image-sizes.ts";
const sizes = Object.fromEntries(
  readdirSync(dir)
    .filter((f) => f.endsWith(".png"))
    .sort()
    .map((f) => [f.replace(/\.png$/, ""), statSync(join(dir, f)).size]),
);
const text = `// Generated by scripts/image-sizes.mjs. Do not edit.\nexport const IMAGE_BYTES: Record<string, number> = ${JSON.stringify(sizes, null, 2)};\n`;
if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);
